-- Credit packs: prepaid bundles of 5, 10, 15 or 20 reservations. The four sizes are fixed (one row each);
-- the owner only sets their total price. Seeded so the price per reservation goes down as the pack grows
-- (15.00, 14.00, 13.00, 12.00 EUR).

CREATE TABLE credit_pack (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pack_size INTEGER       NOT NULL UNIQUE CHECK (pack_size IN (5, 10, 15, 20)),
    price     DECIMAL(8, 2) NOT NULL CHECK (price >= 0)
);

