-- Initial schema. Availability is COMPUTED at read time from
-- schedule/opening_hours - booking/booking_slot - court_block (not stored).

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    first_name    VARCHAR(100) NOT NULL,
    last_name     VARCHAR(100) NOT NULL,
    phone         VARCHAR(30),
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE court (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL UNIQUE,
    type           VARCHAR(20)  NOT NULL,
    price_per_hour DECIMAL(8, 2) NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE schedule (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id              BIGINT  NOT NULL UNIQUE REFERENCES court (id),
    slot_duration_minutes INTEGER NOT NULL
);

CREATE TABLE opening_hours (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT      NOT NULL REFERENCES schedule (id) ON DELETE CASCADE,
    day_of_week VARCHAR(10) NOT NULL,
    open_time   TIME        NOT NULL,
    close_time  TIME        NOT NULL,
    CONSTRAINT chk_opening_hours_range CHECK (open_time < close_time)
);

CREATE TABLE booking (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id     BIGINT        NOT NULL REFERENCES court (id),
    user_id      BIGINT        NOT NULL REFERENCES app_user (id),
    date         DATE          NOT NULL,
    status       VARCHAR(20)   NOT NULL,
    total_price  DECIMAL(8, 2) NOT NULL,
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMP
);

CREATE TABLE booking_slot (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking (id) ON DELETE CASCADE,
    start_time TIME   NOT NULL,
    end_time   TIME   NOT NULL,
    CONSTRAINT chk_booking_slot_range CHECK (start_time < end_time)
);

CREATE TABLE court_block (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id   BIGINT       NOT NULL REFERENCES court (id),
    date       DATE         NOT NULL,
    start_time TIME         NOT NULL,
    end_time   TIME         NOT NULL,
    reason     VARCHAR(255),
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_court_block_range CHECK (start_time < end_time)
);

CREATE INDEX idx_booking_court_date     ON booking (court_id, date);
CREATE INDEX idx_booking_user           ON booking (user_id);
CREATE INDEX idx_court_block_court_date ON court_block (court_id, date);
CREATE INDEX idx_opening_hours_schedule ON opening_hours (schedule_id);
