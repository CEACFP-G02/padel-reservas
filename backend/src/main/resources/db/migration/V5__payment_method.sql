-- Client payment methods. Card data is never stored: the (mocked) payment gateway tokenises the card and
-- only the brand, last 4 digits, expiry and gateway token are kept. Removing a method sets active = FALSE.

CREATE TABLE payment_method (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES app_user (id),
    brand         VARCHAR(20)  NOT NULL,
    last4         VARCHAR(4)   NOT NULL CHECK (CHAR_LENGTH(last4) = 4),
    exp_month     INTEGER      NOT NULL CHECK (exp_month BETWEEN 1 AND 12),
    exp_year      INTEGER      NOT NULL,
    gateway_token VARCHAR(100) NOT NULL UNIQUE,
    is_default    BOOLEAN      NOT NULL DEFAULT FALSE,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_payment_method_user ON payment_method (user_id);
