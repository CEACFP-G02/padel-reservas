-- Credit ledger: 1 credit = 1 prepaid reservation. The balance is the sum of a client's transactions;
-- a PURCHASE adds a pack's size (recording what was charged, the pack size, the card and the gateway
-- charge), a CONSUMPTION subtracts credits. Credits never expire.

CREATE TABLE credit_transaction (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT        NOT NULL REFERENCES app_user (id),
    type              VARCHAR(20)   NOT NULL,
    credits           INTEGER       NOT NULL,
    amount            DECIMAL(8, 2),
    pack_size         INTEGER,
    payment_method_id BIGINT REFERENCES payment_method (id),
    charge_reference  VARCHAR(100),
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((type = 'PURCHASE' AND credits > 0 AND amount >= 0 AND pack_size IS NOT NULL)
        OR (type = 'CONSUMPTION' AND credits < 0))
);

CREATE INDEX idx_credit_transaction_user ON credit_transaction (user_id, created_at);
